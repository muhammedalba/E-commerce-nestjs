import {
  BadRequestException,
  Inject,
  Injectable,
  Logger,
  NotFoundException,
} from '@nestjs/common';
import { InjectModel } from '@nestjs/mongoose';
import { createHash, randomUUID } from 'crypto';
import { promises as fs } from 'fs';
import { Model, Types } from 'mongoose';
import * as path from 'path';
import * as QRCode from 'qrcode';
import sharp from 'sharp';
import { FileUploadService } from 'src/file-upload/file-upload.service';
import { Order } from 'src/order/shared/schemas/Order.schema';
import { SettingsService } from 'src/settings/settings.service';
import { FileAsset } from 'src/shared/schema/file-asset.schema';
import { CacheInvalidationService } from 'src/shared/services/cache-invalidation.service';
import { MulterFileType } from 'src/shared/utils/interfaces/fileInterface';
import { resolveToFilesystem } from 'src/shared/utils/upload-path.util';
import {
  buildInvoiceSnapshot,
  InvoiceOrderInput,
  InvoiceSnapshot,
} from './invoice-data.builder';
import {
  PDF_RENDERER,
  PdfRenderer,
  TYPST_DIR,
} from './renderers/pdf-renderer.interface';
import { Invoice, InvoiceDocument } from './schemas/invoice.schema';

/** How long a worker may hold the generation lease before another takes over. */
const LEASE_MS = 2 * 60_000;
const INVOICE_FOLDER = 'Invoice';
const DEFAULT_LOGO = path.join(TYPST_DIR, 'assets', 'default-logo.png');

/** Another worker is generating this invoice right now: retry later. */
export class InvoiceBusyError extends Error {
  constructor(orderId: string) {
    super(`Invoice for order ${orderId} is being generated by another worker`);
    this.name = 'InvoiceBusyError';
  }
}

export interface IssuedInvoice {
  /** The stored PDF: the same bytes are attached and served. */
  buffer: Buffer;
  filename: string;
  file: FileAsset;
  displayNumber: string;
}

/**
 * Issues an order's tax invoice once: freezes its data in an Invoice record
 * (one per order), renders the PDF, stores it, and mirrors it on the order
 * (`InvoicePdf`) for the storefront and dashboard. Safe to call again and
 * concurrently: the stored PDF is returned instead of a new one.
 */
@Injectable()
export class InvoiceService {
  private readonly logger = new Logger(InvoiceService.name);

  constructor(
    @InjectModel(Invoice.name)
    private readonly invoiceModel: Model<Invoice>,
    @InjectModel(Order.name) private readonly orderModel: Model<Order>,
    private readonly settingsService: SettingsService,
    private readonly fileUploadService: FileUploadService,
    private readonly cacheInvalidation: CacheInvalidationService,
    @Inject(PDF_RENDERER) private readonly renderer: PdfRenderer,
  ) {}

  async generateAndStore(orderId: string): Promise<IssuedInvoice> {
    const invoice = await this.reserve(orderId);
    if (invoice.status === 'generated' && invoice.file) {
      return this.loadStored(invoice);
    }

    // Take the generation lease (free, or expired after a crash)
    const now = new Date();
    const lockId = randomUUID();
    const locked = await this.invoiceModel.findOneAndUpdate(
      {
        _id: invoice._id,
        status: { $ne: 'generated' },
        $or: [{ lockedUntil: null }, { lockedUntil: { $lt: now } }],
      },
      {
        $set: {
          status: 'generating',
          lockId,
          lockedUntil: new Date(now.getTime() + LEASE_MS),
        },
        $inc: { attempts: 1 },
      },
      { new: true },
    );
    if (!locked) {
      const current = await this.invoiceModel.findById(invoice._id);
      if (current?.status === 'generated' && current.file) {
        return this.loadStored(current);
      }
      throw new InvoiceBusyError(orderId);
    }

    let saved: FileAsset | undefined;
    try {
      const buffer = await this.render(locked.snapshot);
      const filename = `${locked.displayNumber}.pdf`;
      saved = await this.fileUploadService.saveFileToDisk(
        {
          buffer,
          originalname: filename,
          mimetype: 'application/pdf',
          fieldname: 'InvoicePdf',
          size: buffer.length,
        } as MulterFileType,
        INVOICE_FOLDER,
      );
      if (!saved?.url) throw new Error('Storage returned no file');

      const committed = await this.invoiceModel.updateOne(
        { _id: locked._id, lockId },
        {
          $set: {
            status: 'generated',
            file: saved,
            fileSha256: sha256(buffer),
            fileSize: buffer.length,
            generatedAt: new Date(),
          },
          $unset: { lockId: 1, lockedUntil: 1, lastError: 1 },
        },
      );
      if (committed.modifiedCount === 0) {
        // Lease lost (expired and taken over): keep the winner's file only
        await this.discard(saved);
        saved = undefined;
        const current = await this.invoiceModel.findById(locked._id);
        if (current?.status === 'generated' && current.file) {
          return this.loadStored(current);
        }
        throw new InvoiceBusyError(orderId);
      }

      this.logger.log(
        `Invoice ${locked.displayNumber} issued for order ${orderId} (${buffer.length} bytes)`,
      );
      await this.mirrorToOrder(orderId, saved);
      return {
        buffer,
        filename,
        file: saved,
        displayNumber: locked.displayNumber,
      };
    } catch (err) {
      if (err instanceof InvoiceBusyError) throw err;
      if (saved) await this.discard(saved);
      const message = (err as Error).message;
      await this.invoiceModel.updateOne(
        { _id: locked._id, lockId },
        {
          $set: { status: 'failed', lastError: message.slice(0, 2000) },
          $unset: { lockId: 1, lockedUntil: 1 },
        },
      );
      this.logger.error(
        `Invoice ${locked.displayNumber} for order ${orderId} failed (attempt ${locked.attempts}): ${message}`,
        (err as Error).stack,
      );
      throw err;
    }
  }

  /**
   * Admin retry of an invoice that is not issued yet: same frozen data and
   * number. An issued invoice is never re-rendered.
   */
  async regenerate(orderId: string): Promise<IssuedInvoice> {
    const invoice = await this.invoiceModel.findOne({
      order: new Types.ObjectId(orderId),
    });
    if (invoice?.status === 'generated') {
      throw new BadRequestException('Invoice already issued');
    }
    return this.generateAndStore(orderId);
  }

  /** Records what the mail server did with the customer email (not delivery). */
  async recordCustomerEmail(
    orderId: string,
    withInvoice: boolean,
    messageId?: string,
  ): Promise<void> {
    await this.invoiceModel.updateOne(
      { order: new Types.ObjectId(orderId) },
      {
        $set: {
          customerEmail: {
            status: withInvoice
              ? 'smtp_accepted'
              : 'smtp_accepted_without_invoice',
            acceptedAt: new Date(),
            messageId,
          },
        },
      },
    );
  }

  /** True when `asset` is the issued invoice of the order (never deleted). */
  async isIssuedInvoiceFile(
    orderId: string,
    asset: FileAsset | string | null | undefined,
  ): Promise<boolean> {
    if (!asset) return false;
    const url = typeof asset === 'string' ? asset : asset.url;
    const invoice = await this.invoiceModel
      .findOne({ order: new Types.ObjectId(orderId) })
      .select('file')
      .lean();
    return !!invoice?.file?.url && sameFile(invoice.file.url, url);
  }

  /** The Invoice record, created with the frozen data on first use. */
  private async reserve(orderId: string): Promise<InvoiceDocument> {
    if (!Types.ObjectId.isValid(orderId)) {
      throw new BadRequestException('Invalid order ID');
    }
    const order = new Types.ObjectId(orderId);
    const existing = await this.invoiceModel.findOne({ order });
    if (existing) return existing;

    // Lean: an old order's missing fields stay missing (no schema defaults)
    const source = (await this.orderModel
      .findById(order)
      .populate([
        { path: 'shippingAddress.country', select: 'name' },
        { path: 'shippingAddress.city', select: 'name' },
        { path: 'shippingAddress.region', select: 'name' },
        // Only read for lines without their own snapshot (old orders)
        { path: 'items.productId', select: 'title' },
        { path: 'items.variantId', select: 'attributes components' },
      ])
      .lean()) as unknown as InvoiceOrderInput | null;
    if (!source) throw new NotFoundException(`Order ${orderId} not found`);

    // Must succeed: the store's details are frozen into the invoice
    const settings = await this.settingsService.getSettings();
    const issuedAt = new Date();
    const snapshot = buildInvoiceSnapshot(source, settings, issuedAt);

    try {
      return await this.invoiceModel.findOneAndUpdate(
        { order },
        {
          $setOnInsert: {
            order,
            invoiceNumber: source.invoiceNumber ?? undefined,
            displayNumber: snapshot.displayNumber,
            issuedAt,
            snapshot,
            status: 'pending',
            attempts: 0,
          },
        },
        { upsert: true, new: true },
      );
    } catch (err) {
      // Two first calls raced on the unique order index: use the winner's
      if ((err as { code?: number }).code === 11000) {
        const winner = await this.invoiceModel.findOne({ order });
        if (winner) return winner;
      }
      throw err;
    }
  }

  private async render(snapshot: InvoiceSnapshot): Promise<Buffer> {
    const [logo, qr] = await Promise.all([
      this.loadLogo(snapshot.logo),
      QRCode.toBuffer(snapshot.qr.payload, {
        errorCorrectionLevel: 'M',
        margin: 0,
        width: 560,
      }),
    ]);
    const pdf = await this.renderer.render(snapshot, { logo, qr });
    if (pdf.subarray(0, 5).toString() !== '%PDF-') {
      throw new Error('Renderer did not return a PDF');
    }
    return pdf;
  }

  /**
   * The frozen logo as PNG (Typst reads no webp), 256px high at most: ~4×
   * its 64px on the invoice, sharp in print without bloating the PDF. An
   * unreadable logo falls back to the default one, logged: the invoice must
   * not wait on it forever.
   */
  private async loadLogo(logo: FileAsset | string | null): Promise<Buffer> {
    const toPng = (bytes: Buffer) =>
      sharp(bytes)
        .resize({ height: 256, withoutEnlargement: true })
        .png()
        .toBuffer();
    const url = typeof logo === 'string' ? logo : logo?.url;
    if (url) {
      try {
        return await toPng(await this.readAsset(url));
      } catch (err) {
        this.logger.warn(
          `Invoice logo ${url} unreadable, using the default: ${(err as Error).message}`,
        );
      }
    }
    return toPng(await fs.readFile(DEFAULT_LOGO));
  }

  /** The stored PDF, checked against the hash taken when it was issued. */
  private async loadStored(invoice: InvoiceDocument): Promise<IssuedInvoice> {
    const file = invoice.file as FileAsset;
    const buffer = await this.readAsset(file.url);
    if (invoice.fileSha256 && sha256(buffer) !== invoice.fileSha256) {
      throw new Error(
        `Stored invoice ${invoice.displayNumber} does not match its hash`,
      );
    }
    // Repairs a mirror a crash may have skipped (no-op otherwise)
    await this.mirrorToOrder(invoice.order.toString(), file);
    return {
      buffer,
      filename: `${invoice.displayNumber}.pdf`,
      file,
      displayNumber: invoice.displayNumber,
    };
  }

  /** Reads a local upload from disk, anything else over HTTP (Cloudinary). */
  private async readAsset(url: string): Promise<Buffer> {
    if (/^https?:\/\//i.test(url)) {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`GET ${url} → ${res.status}`);
      return Buffer.from(await res.arrayBuffer());
    }
    return fs.readFile(resolveToFilesystem(url));
  }

  /**
   * Shows the invoice on the order unless the order already holds a file
   * (e.g. one an admin uploaded): that one is kept, and logged.
   */
  private async mirrorToOrder(orderId: string, file: FileAsset) {
    const res = await this.orderModel.updateOne(
      {
        _id: orderId,
        $or: [{ InvoicePdf: { $exists: false } }, { InvoicePdf: null }],
      },
      { $set: { InvoicePdf: file } },
    );
    if (res.modifiedCount === 0) {
      const order = await this.orderModel
        .findById(orderId)
        .select('InvoicePdf')
        .lean();
      const current = order?.InvoicePdf?.url;
      if (!current || !sameFile(current, file.url)) {
        this.logger.warn(
          `Order ${orderId} already shows another invoice file (${current}); issued ${file.url} kept on the Invoice record only`,
        );
      }
      return;
    }
    try {
      await this.cacheInvalidation.clearResources(['order']);
    } catch (err) {
      this.logger.warn(
        `Failed to clear order cache: ${(err as Error).message}`,
      );
    }
  }

  private async discard(file: FileAsset) {
    try {
      await this.fileUploadService.deleteFile(file);
    } catch (err) {
      this.logger.warn(
        `Could not delete unused invoice file ${file.url}: ${(err as Error).message}`,
      );
    }
  }
}

function sha256(buffer: Buffer): string {
  return createHash('sha256').update(buffer).digest('hex');
}

/** Same stored file, whether or not BASE_URL was prepended for the client. */
function sameFile(a: string, b: string): boolean {
  return a === b || a.endsWith(b) || b.endsWith(a);
}
