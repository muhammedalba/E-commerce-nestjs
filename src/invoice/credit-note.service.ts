/** Another worker is generating this credit note right now: retry later. */
export class CreditNoteBusyError extends Error {
  constructor(context: string) {
    super(`Credit note for ${context} is being generated by another worker`);
    this.name = 'CreditNoteBusyError';
  }
}

export type CreditNoteRefund = NonNullable<CreditNote['refund']>;

/** What the dashboard needs to offer a return. */
export interface CreditNoteSummary {
  /** No credit note before the invoice itself is issued. */
  invoiceIssued: boolean;
  /** Per order line: how many can still be returned. */
  remaining: number[];
  /** Refunded already (Moyasar dashboard, direct API) with no credit note yet. */
  uncreditedRefund: number;
  /**
   * An older order with a coupon on some items only: each line's discount is
   * estimated from the coupon's current rules (they may have changed since
   * the purchase). The admin should check the amount.
   */
  discountEstimated: boolean;
}

type OrderForCredit = CreditOrderInput &
  InvoiceOrderInput & { refundedAmount?: number; couponId?: Types.ObjectId };

/** A defect return with no shipping priced for its lines. */
const DEFECT: ReturnPolicyInput = { reasonType: 'defect', returnShipping: 0 };

/** A reference's id, whether populated (`{ _id }`) or not. */
const refId = (ref: unknown): string =>
  String(ref && typeof ref === 'object' && '_id' in ref ? ref._id : ref);

/**
 * Tax credit notes (مرتجع ضريبي) against an order's issued invoice: reserves
 * the returned lines (so two returns never take the same items), numbers the
 * credit note once its refund went through, and renders its PDF like the
 * invoice. Money, stock and emails are the caller's (OrderCreditNoteService).
 */
@Injectable()
export class CreditNoteService {
  private readonly logger = new Logger(CreditNoteService.name);
  private readonly issuer: PdfDocumentIssuer;

  constructor(
    @InjectModel(CreditNote.name)
    private readonly creditNoteModel: Model<CreditNote>,
    @InjectModel(Invoice.name) private readonly invoiceModel: Model<Invoice>,
    @InjectModel(Order.name) private readonly orderModel: Model<Order>,
    @InjectModel(Coupon.name) private readonly couponModel: Model<Coupon>,
    @InjectConnection() private readonly connection: Connection,
    private readonly settingsService: SettingsService,
    private readonly cacheInvalidation: CacheInvalidationService,
    fileUploadService: FileUploadService,
    @Inject(PDF_RENDERER) renderer: PdfRenderer,
  ) {
    this.issuer = new PdfDocumentIssuer(
      creditNoteModel,
      renderer,
      fileUploadService,
      this.logger,
      {
        folder: 'CreditNote',
        label: 'Credit note',
        busyError: (context) => new CreditNoteBusyError(context),
        onStored: () => this.clearOrderCache(),
      },
    );
  }

  /** An issued credit note (what its email needs), or null. */
  findIssued(noteId: string) {
    if (!Types.ObjectId.isValid(noteId)) return Promise.resolve(null);
    return this.creditNoteModel
      .findOne({ _id: noteId, state: 'issued' })
      .select('order displayNumber amounts deductions snapshot refund')
      .lean();
  }

  /** The order's credit notes, newest first (void ones left out). */
  listForOrder(orderId: string) {
    return this.creditNoteModel
      .find({ order: new Types.ObjectId(orderId), state: { $ne: 'void' } })
      .select(
        'displayNumber state issuedAt lines amounts reason reasonType deductions returnRequest source refund restocked status file',
      )
      .sort({ createdAt: -1 })
      .lean();
  }

  /**
   * What a return can take now: whether the invoice is issued, how many of
   * each line are left, and refunded money no credit note covers yet.
   */
  async summary(orderId: string): Promise<CreditNoteSummary> {
    const { order, invoice, prior, issued, discountEstimated } =
      await this.load(orderId);
    return {
      invoiceIssued: !!invoice,
      remaining: remainingQuantities(order, prior),
      uncreditedRefund: this.uncredited(order, issued),
      discountEstimated,
    };
  }

  /**
   * The amounts a return would have, without saving anything. `policy`:
   * the reason and the returned lines' shipping (priced by the caller,
   * OrderCreditNoteService.returnShipping), see credit-note.calculator.ts.
   */
  async preview(
    orderId: string,
    lines: RequestedLine[],
    policy: ReturnPolicyInput = DEFECT,
  ): Promise<
    CreditNoteCalculation & {
      uncreditedRefund: number;
      discountEstimated: boolean;
    }
  > {
    const { order, invoice, prior, issued, discountEstimated } =
      await this.load(orderId);
    if (!invoice)
      throw new BadRequestException('The invoice is not issued yet');
    return {
      ...this.calculate(order, invoice, prior, lines, policy),
      uncreditedRefund: this.uncredited(order, issued),
      discountEstimated,
    };
  }

  /**
   * Creates the credit note in `awaiting_refund`, which reserves its lines:
   * inside a transaction that also bumps the invoice's counter, so two
   * returns of the same order run one after the other. `lines: 'all'` returns
   * everything not returned yet (a full refund); null when nothing is left.
   * A repeated `idempotencyKey` returns the credit note it already created.
   * `meta.policy` (default: defect, no shipping priced) decides who pays the
   * shipping; `lines: 'all'` empties the order, so a defect needs none.
   */
  async reserve(
    orderId: string,
    lines: RequestedLine[] | 'all',
    meta: Pick<CreditNote, 'reason' | 'source' | 'restock'> & {
      policy?: ReturnPolicyInput;
      returnRequest?: Types.ObjectId;
      createdBy?: string;
      idempotencyKey?: string;
    },
  ): Promise<CreditNoteDocument | null> {
    if (meta.idempotencyKey) {
      const existing = await this.creditNoteModel.findOne({
        idempotencyKey: meta.idempotencyKey,
      });
      if (existing) return existing;
    }
    const { order, invoice } = await this.load(orderId);
    if (!invoice)
      throw new BadRequestException('The invoice is not issued yet');
    const policy = meta.policy ?? DEFECT;

    try {
      return await withTransactionRetry(
        async (session) => {
          await this.invoiceModel.updateOne(
            { _id: invoice._id },
            { $inc: { creditNoteSeq: 1 } },
            { session },
          );
          const prior = await this.creditNoteModel
            .find({ order: order._id, state: { $ne: 'void' } })
            .select('lines amounts')
            .session(session)
            .lean();
          const requested =
            lines === 'all' ? allRemainingLines(order, prior) : lines;
          if (requested.length === 0) return null;
          const calc = this.calculate(order, invoice, prior, requested, policy);
          const [note] = await this.creditNoteModel.create(
            [
              {
                order: order._id,
                invoice: invoice._id,
                state: 'awaiting_refund',
                lines: calc.lines,
                amounts: calc.amounts,
                includesCharges: calc.includesCharges,
                deductions: calc.deductions,
                reason: meta.reason,
                reasonType: policy.reasonType,
                returnRequest: meta.returnRequest,
                source: meta.source,
                restock: meta.restock,
                createdBy: meta.createdBy
                  ? new Types.ObjectId(meta.createdBy)
                  : undefined,
                idempotencyKey: meta.idempotencyKey,
              },
            ],
            { session },
          );
          return note;
        },
        this.connection,
        this.logger,
      );
    } catch (err) {
      // The same full refund recorded twice at once: the first one wins
      if ((err as { code?: number }).code === 11000 && meta.idempotencyKey) {
        return this.creditNoteModel.findOne({
          idempotencyKey: meta.idempotencyKey,
        });
      }
      throw err;
    }
  }

  /**
   * The refund went through: numbers the credit note (no gaps: a void one
   * never takes a number) and freezes what its PDF shows.
   */
  async issue(
    noteId: Types.ObjectId,
    refund: CreditNoteRefund,
  ): Promise<CreditNoteDocument> {
    const note = await this.creditNoteModel.findById(noteId);
    if (!note) throw new NotFoundException('Credit note not found');
    if (note.state === 'issued') return note;
    if (note.state === 'void') {
      throw new BadRequestException('This credit note was cancelled');
    }

    const [invoice, order, settings] = await Promise.all([
      this.invoiceModel.findById(note.invoice).lean(),
      this.loadOrder(note.order.toString()),
      this.settingsService.getSettings(),
    ]);
    if (!invoice || !order) throw new NotFoundException('Invoice not found');

    const { timezone } = resolveStoreTimezone(
      settings.businessAddress,
      'Asia/Riyadh',
    );
    const counter = await this.connection
      .collection<{ _id: string; seq: number }>('counters')
      .findOneAndUpdate(
        { _id: 'creditNoteNumber' },
        { $inc: { seq: 1 } },
        { upsert: true, returnDocument: 'after' },
      );
    const serial = counter?.seq ?? 1;
    const issuedAt = new Date();
    const displayNumber = creditNoteDisplayNumber(serial, issuedAt, timezone);
    const snapshot = buildCreditNoteSnapshot({
      invoice,
      order,
      note: {
        displayNumber,
        issuedAt,
        lines: note.lines,
        amounts: note.amounts,
        reasonType: note.reasonType,
        deductions: note.deductions,
      },
      timezone,
    });

    const updated = await this.creditNoteModel.findOneAndUpdate(
      { _id: note._id, state: 'awaiting_refund' },
      {
        $set: {
          state: 'issued',
          creditNoteNumber: serial,
          displayNumber,
          issuedAt,
          snapshot,
          refund,
        },
      },
      { new: true },
    );
    if (!updated) {
      // Issued meanwhile by another call: keep that one (this serial is unused)
      const current = await this.creditNoteModel.findById(note._id);
      if (current?.state === 'issued') return current;
      throw new BadRequestException('This credit note was cancelled');
    }
    this.logger.log(
      `Credit note ${displayNumber} issued for order ${note.order.toString()} (${note.amounts.total})`,
    );
    await this.clearOrderCache();
    return updated;
  }

  /** The refund failed: frees the lines; the credit note never had a number. */
  async void(noteId: Types.ObjectId, reason: string): Promise<void> {
    await this.creditNoteModel.updateOne(
      { _id: noteId, state: 'awaiting_refund' },
      { $set: { state: 'void', voidReason: reason.slice(0, 2000) } },
    );
  }

  /** Its lines are back in stock: never restocked twice (retries, repairs). */
  async markRestocked(noteId: Types.ObjectId): Promise<void> {
    await this.creditNoteModel.updateOne(
      { _id: noteId },
      { $set: { restocked: true } },
    );
  }

  /** The credit note's PDF: rendered and stored once, then read back. */
  async generateAndStore(noteId: string): Promise<IssuedPdf> {
    const note = await this.creditNoteModel.findById(noteId);
    if (!note || note.state !== 'issued' || !note.snapshot) {
      throw new NotFoundException(`Credit note ${noteId} is not issued`);
    }
    return this.issuer.issue(
      note as unknown as Parameters<PdfDocumentIssuer['issue']>[0],
      `credit note ${noteId}`,
    );
  }

  /** Admin retry of a PDF that could not be rendered (same data and number). */
  async regenerate(orderId: string, noteId: string): Promise<IssuedPdf> {
    const note = await this.creditNoteModel.findOne({
      _id: noteId,
      order: new Types.ObjectId(orderId),
    });
    if (!note) throw new NotFoundException('Credit note not found');
    if (note.status === 'generated') {
      throw new BadRequestException('Credit note already generated');
    }
    return this.generateAndStore(noteId);
  }

  /** Records what the mail server did with the customer email (not delivery). */
  async recordCustomerEmail(
    noteId: string,
    withPdf: boolean,
    messageId?: string,
  ): Promise<void> {
    await this.creditNoteModel.updateOne(
      { _id: noteId },
      {
        $set: {
          customerEmail: {
            status: withPdf ? 'smtp_accepted' : 'smtp_accepted_without_invoice',
            acceptedAt: new Date(),
            messageId,
          },
        },
      },
    );
  }

  private calculate(
    order: OrderForCredit,
    invoice: { snapshot: { amounts: { grandTotal: number; tax: number } } },
    prior: PriorCreditNote[],
    lines: RequestedLine[],
    policy: ReturnPolicyInput,
  ): CreditNoteCalculation {
    try {
      return calculateCreditNote(
        order,
        invoice.snapshot.amounts,
        prior,
        lines,
        policy,
      );
    } catch (err) {
      if (err instanceof CreditNoteError) {
        throw new BadRequestException(err.message);
      }
      throw err;
    }
  }

  /**
   * Refunded money no credit note accounts for yet (refunded from the
   * Moyasar dashboard or the refund API directly): a new credit note
   * uses it before refunding more.
   */
  private uncredited(
    order: OrderForCredit,
    issued: {
      amounts: { total: number };
      deductions?: CreditNote['deductions'];
      refund?: CreditNoteRefund;
    }[],
  ): number {
    const credited = issued
      .filter((n) => n.refund?.via !== 'none')
      .reduce((sum, n) => sum + refundableAmount(n), 0);
    return Math.max(0, cleanMoney((order.refundedAmount || 0) - credited));
  }

  /**
   * The order (lean), its issued invoice (null while not issued) and its
   * credit notes that count: `prior` (not void, reserving lines) and
   * `issued` (numbered).
   */
  private async load(orderId: string) {
    if (!Types.ObjectId.isValid(orderId)) {
      throw new BadRequestException('Invalid order ID');
    }
    const [order, invoice, notes] = await Promise.all([
      this.loadOrder(orderId),
      this.invoiceModel
        .findOne({ order: new Types.ObjectId(orderId), status: 'generated' })
        .lean(),
      this.creditNoteModel
        .find({ order: new Types.ObjectId(orderId), state: { $ne: 'void' } })
        .select('lines amounts deductions state refund')
        .lean(),
    ]);
    if (!order) throw new NotFoundException(`Order ${orderId} not found`);
    const { lineDiscounts, discountEstimated } =
      await this.estimateLineDiscounts(order);
    return {
      order: lineDiscounts ? { ...order, lineDiscounts } : order,
      invoice,
      prior: notes,
      issued: notes.filter((n) => n.state === 'issued'),
      discountEstimated,
    };
  }

  /**
   * Each line's coupon share for an order from before checkout froze it on
   * the lines (`items[].discount`). Newer orders, orders with no discount
   * and coupons on the whole order need none (the calculator's proportional
   * share is exact for those). A coupon on some items: its current rules
   * applied to the lines' frozen product, brand and category (estimated: the
   * rules may have changed). A deleted coupon, or rules that no longer match
   * any line: the proportional share, also flagged as estimated.
   */
  private async estimateLineDiscounts(order: OrderForCredit): Promise<{
    lineDiscounts?: number[];
    discountEstimated: boolean;
  }> {
    const discount = order.discountAmount || 0;
    const frozen = order.items.some((item) => item.discount !== undefined);
    if (discount <= 0 || frozen) return { discountEstimated: false };

    const coupon = order.couponId
      ? await this.couponModel
          .findById(order.couponId)
          .select('applyTo applyItems')
          .lean()
      : null;
    if (coupon?.applyTo === 'all') return { discountEstimated: false };
    if (!coupon) return { discountEstimated: true };

    const eligible = order.items.map((item) => {
      // Frozen on the line at checkout (ids)
      const { brand, category } = item as { brand?: string; category?: string };
      return isCouponEligible(coupon, {
        productId: refId(item.productId),
        brand,
        category,
      });
    });
    if (!eligible.some(Boolean)) return { discountEstimated: true };
    return {
      lineDiscounts: allocateCouponDiscount(
        discount,
        order.items.map((item, i) => ({
          price: item.price || 0,
          quantity: item.quantity || 1,
          eligible: eligible[i],
        })),
      ),
      discountEstimated: true,
    };
  }

  /** Lean (no schema defaults), like the invoice reads it. */
  private async loadOrder(orderId: string) {
    return (await this.orderModel
      .findById(orderId)
      .populate([
        { path: 'items.productId', select: 'title' },
        {
          path: 'items.variantId',
          select: 'attributes components shippingProfile',
        },
      ])
      .lean()) as unknown as (OrderForCredit & { _id: Types.ObjectId }) | null;
  }

  /** Order pages show credit notes: their cached responses must go. */
  private async clearOrderCache() {
    try {
      await this.cacheInvalidation.clearResources(['order']);
    } catch (err) {
      this.logger.warn(
        `Failed to clear order cache: ${(err as Error).message}`,
      );
    }
  }
}
